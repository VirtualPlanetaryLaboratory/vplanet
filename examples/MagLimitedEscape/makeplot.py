#!/usr/bin/env python3
"""Two figures for the Gunell+2018 magnetic-limited escape example.

(1) Earth_4Panel.png - four-panel time evolution of the constant-B and
    thermint-coupled Earth runs, using vplot's accessible palette.
(2) T1e_Reproduction.png - magnetic-moment sweep for Trappist-1e in
    notebook style, generated by notebook_comparison.py."""

import os
import subprocess
import sys

import matplotlib.pyplot as plt
import numpy as np

import vplot
from vplot import colors as vp

THIS_DIR = os.path.dirname(os.path.abspath(__file__))
PROTON_MASS_KG = 1.67e-27

EARTH_CONST_FORWARD = os.path.join(
    THIS_DIR, "earth_const", "earth_const.earth.forward")
EARTH_THERMINT_FORWARD = os.path.join(
    THIS_DIR, "earth_thermint", "earth_thermint.earth.forward")

COLS_CONST = {
    "Time": 0, "MagField": 1, "Pickup": 3, "CrossField": 4,
    "PolarCap": 5, "Cusp": 6, "Driscoll": 7,
}
COLS_THERMINT = {
    "Time": 0, "MagMom": 1, "MagField": 2, "Pickup": 4, "CrossField": 5,
    "PolarCap": 6, "Cusp": 7, "Driscoll": 8, "TMan": 14, "TCore": 15,
    "RIC": 16,
}

MECHANISMS = ["Pickup", "CrossField", "PolarCap", "Cusp", "Driscoll"]
MECHANISM_COLORS = {
    "Pickup": vp.orange,
    "CrossField": vp.dark_blue,
    "PolarCap": vp.purple,
    "Cusp": vp.red,
    "Driscoll": vp.pale_blue,
}

# Bumped from the vplot defaults so the panels remain readable when
# rendered at 6.5 inches per column.
RC_OVERRIDES = {
    "axes.labelsize": 17,
    "xtick.labelsize": 14,
    "ytick.labelsize": 14,
    "legend.fontsize": 12,
    "lines.linewidth": 2.0,
}


def fdaLoadForward(sPath):
    """Read a vplanet forward file as a 2-D numpy array."""
    return np.loadtxt(sPath)


def fdaPositiveOrNan(daValues):
    """Replace non-positive values with NaN so log plots mask them."""
    return np.where(daValues > 0, daValues, np.nan)


def fnPlotMassLossPanel(ax, daConstRows, daThermRows):
    """Per-mechanism mass loss rate, both Earth runs overlaid."""
    daTimeConstGyr = daConstRows[:, COLS_CONST["Time"]] / 1e9
    daTimeThermGyr = daThermRows[:, COLS_THERMINT["Time"]] / 1e9
    for sMechanism in MECHANISMS:
        sColor = MECHANISM_COLORS[sMechanism]
        daConstParticles = np.abs(daConstRows[:, COLS_CONST[sMechanism]])
        daThermParticles = np.abs(daThermRows[:, COLS_THERMINT[sMechanism]])
        daConstKgPerSec = fdaPositiveOrNan(daConstParticles * PROTON_MASS_KG)
        daThermKgPerSec = fdaPositiveOrNan(daThermParticles * PROTON_MASS_KG)
        ax.plot(daTimeConstGyr, daConstKgPerSec, color=sColor, linestyle="-",
                label=f"{sMechanism} (const B)")
        ax.plot(daTimeThermGyr, daThermKgPerSec, color=sColor, linestyle="--",
                label=f"{sMechanism} (thermint B)")
    ax.set_yscale("log")
    ax.set_xlabel("Time (Gyr)")
    ax.set_ylabel("Hydrogen mass loss rate (kg s$^{-1}$)")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=10, ncol=2, loc="lower right")


def fnPlotMagFieldPanel(ax, daConstRows, daThermRows):
    """Magnetic dipole strength."""
    daTimeConstGyr = daConstRows[:, COLS_CONST["Time"]] / 1e9
    daTimeThermGyr = daThermRows[:, COLS_THERMINT["Time"]] / 1e9
    daConstField = daConstRows[:, COLS_CONST["MagField"]]
    daThermField = daThermRows[:, COLS_THERMINT["MagField"]]
    ax.plot(daTimeConstGyr, daConstField, color=vp.dark_blue, linestyle="-",
            label="Constant B")
    ax.plot(daTimeThermGyr, daThermField, color=vp.orange, linestyle="--",
            label="Thermint dynamo")
    ax.set_xlabel("Time (Gyr)")
    ax.set_ylabel("Dipole moment (Earth dipoles)")
    ax.grid(alpha=0.3)
    ax.legend()


def fnPlotCoreTemperaturePanel(ax, daThermRows):
    """Core temperature (thermint run only)."""
    daTimeGyr = daThermRows[:, COLS_THERMINT["Time"]] / 1e9
    daTCore = daThermRows[:, COLS_THERMINT["TCore"]]
    ax.plot(daTimeGyr, daTCore, color=vp.red)
    ax.set_xlabel("Time (Gyr)")
    ax.set_ylabel("Core temperature (K)")
    ax.grid(alpha=0.3)


def fnPlotInnerCoreRadiusPanel(ax, daThermRows):
    """Inner core radius (thermint run only)."""
    daTimeGyr = daThermRows[:, COLS_THERMINT["Time"]] / 1e9
    daRIC = daThermRows[:, COLS_THERMINT["RIC"]]
    ax.plot(daTimeGyr, daRIC, color=vp.purple)
    ax.set_xlabel("Time (Gyr)")
    ax.set_ylabel("Inner core radius (km)")
    ax.grid(alpha=0.3)


def fnSaveEarthFigure(sOutputPath):
    """Build and write the four-panel Earth comparison figure."""
    daConstRows = fdaLoadForward(EARTH_CONST_FORWARD)
    daThermRows = fdaLoadForward(EARTH_THERMINT_FORWARD)
    with plt.rc_context(RC_OVERRIDES):
        fig, axes = plt.subplots(2, 2, figsize=(15, 10))
        fnPlotMassLossPanel(axes[0, 0], daConstRows, daThermRows)
        fnPlotMagFieldPanel(axes[0, 1], daConstRows, daThermRows)
        fnPlotCoreTemperaturePanel(axes[1, 0], daThermRows)
        fnPlotInnerCoreRadiusPanel(axes[1, 1], daThermRows)
        fig.tight_layout()
        fig.savefig(sOutputPath, dpi=150)
    print(f"Wrote {sOutputPath}")


def fnRegenerateT1eFigure(sOutputPath):
    """Run the T1e magnetic-moment reproduction script."""
    sScript = os.path.join(THIS_DIR, "notebook_comparison.py")
    subprocess.run([sys.executable, sScript, sOutputPath],
                   check=True, cwd=THIS_DIR)


if __name__ == "__main__":
    fnSaveEarthFigure(os.path.join(THIS_DIR, "Earth_4Panel.png"))
    fnRegenerateT1eFigure(os.path.join(THIS_DIR, "T1e_Reproduction.png"))
