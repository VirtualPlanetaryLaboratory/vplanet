class Test_AtmescThermintCouplingEqtide:
    """The ATMESC<->THERMINT magnetic coupling must survive EQTIDE.

    The benchmark above pins final values, but an opaque number regressing
    does not say why. These assert the coupling contract directly: with
    EQTIDE active, PropsAuxAtmescThermint must still run, so dMagField
    follows the THERMINT geodynamo prediction and the Gunell magnetopause
    tracks it. When the hook is skipped, MagField sticks at its dMagField
    input (1 Earth dipole) and MagPauseRadAtmEsc is flat.
    """

    def test_magfield_tracks_magmom(self, vplanet_output):
        # Both are reported in EMAGMOM, so they are directly comparable.
        magmom = vplanet_output.earth.MagMom
        magfield = vplanet_output.earth.MagField
        assert np.allclose(magfield, magmom, rtol=1e-6), (
            "MagField must follow THERMINT's MagMom every step; a constant "
            "MagField means PropsAuxAtmescThermint was not registered."
        )

    def test_magmom_actually_evolves(self, vplanet_output):
        # Guards the test itself: if the dynamo were flat, tracking above
        # would pass trivially.
        magmom = vplanet_output.earth.MagMom.value
        assert magmom.max() - magmom.min() > 0.1 * abs(magmom[0])

    def test_magnetopause_is_not_constant(self, vplanet_output):
        radmp = vplanet_output.earth.MagPauseRadAtmEsc.value
        assert radmp.max() - radmp.min() > 0.05 * abs(radmp[0]), (
            "MagPauseRadAtmEsc is constant -- the Gunell standoff radius is "
            "not seeing the evolving dipole moment."
        )
